import data from './words.json';
import grammar from './grammar.json';

export interface Word {
  id: string;
  text: string;
  language: 'en' | 'fr';
  /** Sentence used to give context when the user asks for a hint */
  sentence: string;
  /** Hand-authored sound-based spelling chunks, e.g. ["ad","ver","tise","ment"] */
  chunks?: string[];
  /** French only: deck category id (see categories.ts) */
  category?: string;
  /** French TCF words: the spelling cue from the source list */
  cue?: string;
  /** grammar exercises: fill-in-the-blank items (sentence holds the ___ blank) */
  kind?: 'grammar';
  /** grammar: one-line explanation shown after answering */
  rule?: string;
  /** grammar: other fully-correct answers for the blank */
  alt?: string[];
}

export const WORDS = [...(data as Word[]), ...(grammar as Word[])];

